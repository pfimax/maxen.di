using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Maxen.DI.Generators
{
    /// <summary>Writes the module initializer that hands every collected constructor call to the container's shelf.</summary>
    internal static class ActivatorEmitter
    {
        public static void Emit(SourceProductionContext context, ImmutableArray<ActivatorModel?> models, string assemblyName)
        {
            // The same type is usually registered more than once (and from several files); one entry is plenty.
            var distinct = models.Where(m => m != null).Select(m => m!)
                .GroupBy(m => m.SortKey)
                .Select(g => g.First())
                .OrderBy(m => m.SortKey, System.StringComparer.Ordinal)
                .ToList();

            if (distinct.Count == 0) return;

            var code = new StringBuilder();
            code.AppendLine("// <auto-generated/>");
            code.AppendLine("// Produced by Maxen.DI.Generators. Do not edit: changes are lost on the next build.");
            code.AppendLine("#nullable enable");
            code.AppendLine();
            code.Append("namespace ").AppendLine(SourceEmitter.NamespaceFor(assemblyName));
            code.AppendLine("{");
            code.AppendLine("    internal static class GeneratedActivatorRegistration");
            code.AppendLine("    {");
            code.AppendLine("        /// <summary>Runs once when the assembly loads, before any container exists.</summary>");
            code.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            code.AppendLine("        internal static void Register()");
            code.AppendLine("        {");
            foreach (var model in distinct) code.Append(model.Code);
            code.AppendLine("        }");
            code.AppendLine("    }");
            code.AppendLine("}");

            context.AddSource("MaxenGeneratedActivators.g.cs", code.ToString());
        }
    }
}
