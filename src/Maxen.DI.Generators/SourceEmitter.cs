using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Maxen.DI.Generators
{
    /// <summary>Writes the generated registration class and reports problems found along the way.</summary>
    internal static class SourceEmitter
    {
        public static void Emit(SourceProductionContext context, ImmutableArray<ServiceModel> models, string assemblyName)
        {
            var problems = models.Where(m => m.Diagnostic is not null).Select(m => m.Diagnostic!)
                .Concat(CaptiveDependencyChecker.Check(models));

            foreach (var diagnostic in problems)
            {
                var arguments = diagnostic.Argument.Split('|');
                context.ReportDiagnostic(Diagnostic.Create(
                    diagnostic.Descriptor, diagnostic.Location.ToLocation(), arguments.Cast<object>().ToArray()));
            }

            var code = new StringBuilder();
            code.AppendLine("// <auto-generated/>");
            code.AppendLine("// Produced by Maxen.DI.Generators. Do not edit: changes are lost on the next build.");
            code.AppendLine("#nullable enable");
            code.AppendLine();
            code.Append("namespace ").AppendLine(NamespaceFor(assemblyName));
            code.AppendLine("{");
            code.AppendLine("    internal static class GeneratedRegistrations");
            code.AppendLine("    {");
            code.AppendLine("        /// <summary>Registers every class marked with [Service] in this assembly, without using reflection.</summary>");
            code.AppendLine("        internal static global::Maxen.DI.ContainerBuilder RegisterGeneratedServices(this global::Maxen.DI.ContainerBuilder builder)");
            code.AppendLine("        {");

            // A stable order keeps the output (and the resolution order of duplicates) the same from build to build.
            foreach (var model in models.Where(m => m.Statement is not null).OrderBy(m => m.SortKey, System.StringComparer.Ordinal))
                code.Append("            ").AppendLine(model.Statement);

            code.AppendLine("            return builder;");
            code.AppendLine("        }");
            code.AppendLine("    }");
            code.AppendLine("}");

            context.AddSource("MaxenGeneratedRegistrations.g.cs", code.ToString());
        }

        /// <summary>Turns an assembly name such as "My-App.Core" into a legal namespace.</summary>
        internal static string NamespaceFor(string assemblyName)
        {
            var parts = assemblyName.Split('.').Select(part =>
            {
                var clean = new string(part.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
                return clean.Length == 0 || char.IsDigit(clean[0]) ? "_" + clean : clean;
            });
            return string.Join(".", parts);
        }
    }
}
