using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Maxen.DI.Generators
{
    /// <summary>Writes the proxy classes and the module initializer that puts their factories on the container's shelf.</summary>
    internal static class ProxyEmitter
    {
        public static void Emit(SourceProductionContext context, ImmutableArray<ProxyModel?> models, string assemblyName)
        {
            // An interface is usually intercepted from several places; one proxy class is enough.
            var distinct = models.Where(m => m != null).Select(m => m!)
                .GroupBy(m => m.SortKey)
                .Select(g => g.First())
                .OrderBy(m => m.SortKey, System.StringComparer.Ordinal)
                .ToList();

            if (distinct.Count == 0) return;

            var code = new StringBuilder();
            code.AppendLine("// <auto-generated/>");
            code.AppendLine("// Produced by Maxen.DI.Generators. Do not edit: changes are lost on the next build.");
            code.AppendLine();
            code.Append("namespace ").AppendLine(SourceEmitter.NamespaceFor(assemblyName));
            code.AppendLine("{");

            // Numbered in sorted order, so names (and the whole file) stay the same from build to build.
            for (var i = 0; i < distinct.Count; i++)
                code.AppendLine(distinct[i].ClassBody.Replace("{CLASS}", "GeneratedProxy" + i));

            code.AppendLine("    internal static class GeneratedProxyRegistration");
            code.AppendLine("    {");
            code.AppendLine("        /// <summary>Runs once when the assembly loads, before any container exists.</summary>");
            code.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            code.AppendLine("        internal static void Register()");
            code.AppendLine("        {");
            for (var i = 0; i < distinct.Count; i++)
                code.AppendLine("            global::Maxen.DI.Interception.GeneratedProxies.Add(typeof(" + distinct[i].InterfaceName
                    + "), static (target, interceptors) => new GeneratedProxy" + i + "(target, interceptors));");
            code.AppendLine("        }");
            code.AppendLine("    }");
            code.AppendLine("}");

            context.AddSource("MaxenGeneratedProxies.g.cs", code.ToString());
        }
    }
}
